def test_plugin_registration_order_follows_config(tmp_path):
    from golem.config import GolemConfig

    # Create two plugins that modify raw content
    (tmp_path / "plugin_a.py").write_text(
        """\
from golem.plugins import hookimpl

@hookimpl
def on_pre_parse(raw_content: str) -> str:
    return raw_content + " -> [A]"
""",
        encoding="utf-8",
    )

    (tmp_path / "plugin_b.py").write_text(
        """\
from golem.plugins import hookimpl

@hookimpl
def on_pre_parse(raw_content: str) -> str:
    return raw_content + " -> [B]"
""",
        encoding="utf-8",
    )

    # config.plugins in order A, then B -> Pluggy registers A then B (so B hook runs first, A second)
    config_ab = GolemConfig(plugins=["plugin_a", "plugin_b"])
    pm_ab = get_plugin_manager(config=config_ab, plugins_dir=tmp_path)
    res_ab = pm_ab.hook.on_pre_parse(raw_content="start")
    assert res_ab == ["start -> [B]", "start -> [A]"]

    # config.plugins in order B, then A -> Pluggy registers B then A (so A hook runs first, B second)
    config_ba = GolemConfig(plugins=["plugin_b", "plugin_a"])
    pm_ba = get_plugin_manager(config=config_ba, plugins_dir=tmp_path)
    res_ba = pm_ba.hook.on_pre_parse(raw_content="start")
    assert res_ba == ["start -> [A]", "start -> [B]"]


def test_get_plugin_manager_caches_entry_points(monkeypatch):
    """Verify get_plugin_manager caches entry point discovery across multiple calls."""
    import importlib.metadata
    from golem.plugins import get_plugin_manager

    # First call warms or uses the cache
    pm1 = get_plugin_manager()
    assert pm1 is not None

    # Spy on entry_points to ensure subsequent calls do not scan disk
    ep_call_count = 0
    orig_ep = importlib.metadata.entry_points

    def spy_ep(*args, **kwargs):
        nonlocal ep_call_count
        ep_call_count += 1
        return orig_ep(*args, **kwargs)

    monkeypatch.setattr(importlib.metadata, "entry_points", spy_ep)

    pm2 = get_plugin_manager()
    pm3 = get_plugin_manager()

    assert pm2 is not None
    assert pm3 is not None
    # Entry points should not have been scanned again
    assert ep_call_count == 0


def test_uniform_class_resolution_with_from_config(tmp_path, monkeypatch):
    """Verify get_plugin_manager resolves a class plugin with from_config."""
    from golem.config import GolemConfig
    from golem.plugins import get_plugin_manager

    pkg_dir = tmp_path / "custom_class_pkg"
    pkg_dir.mkdir()
    (pkg_dir / "__init__.py").write_text("", encoding="utf-8")
    (pkg_dir / "plugin.py").write_text(
        """\
from typing import Any
from golem.plugins import hookimpl, GolemPlugin

class ConfigurablePlugin(GolemPlugin):
    name = "custom_class_pkg.configurable"

    def __init__(self, greeting: str = "hello") -> None:
        super().__init__(greeting=greeting)
        self.greeting = greeting

    @classmethod
    def from_config(cls, config: Any = None) -> "ConfigurablePlugin":
        plugin_configs = getattr(config, "plugin_configs", {}) or {}
        cfg = plugin_configs.get("custom_class_pkg.configurable", {})
        return cls(**cfg)

    @hookimpl
    def on_pre_parse(self, raw_content: str) -> str:
        return f"{self.greeting}: {raw_content}"
""",
        encoding="utf-8",
    )
    monkeypatch.syspath_prepend(str(tmp_path))

    config = GolemConfig(
        plugins=["custom_class_pkg.plugin:ConfigurablePlugin"],
        plugin_configs={"custom_class_pkg.configurable": {"greeting": "howdy"}},
    )
    pm = get_plugin_manager(config=config)
    plugin = pm.get_plugin("custom_class_pkg.plugin:ConfigurablePlugin")
    assert plugin is not None
    assert plugin.greeting == "howdy"
    res = pm.hook.on_pre_parse(raw_content="world")
    assert "howdy: world" in res


