def test_plugin_hook_execution_in_build_pipeline(tmp_path):
    from golem.config import GolemConfig
    from golem.engine import BuildEngine

    # Scaffold temporary site
    content = tmp_path / "content"
    content.mkdir()
    (content / "index.adoc").write_text("This is draft content.\n", encoding="utf-8")

    # Create plugins folder and write a local hook plugin
    plugins_dir = tmp_path / "plugins"
    plugins_dir.mkdir()
    plugin_code = """
from golem.plugins import hookimpl

@hookimpl
def on_pre_parse(raw_content: str) -> str:
    return raw_content.replace("draft", "final")

@hookimpl
def on_post_render(html_content: str) -> str:
    return html_content.replace("Generated by Golem", "Generated by Golem and Plugin")
"""
    (plugins_dir / "test_hook.py").write_text(plugin_code, encoding="utf-8")

    # Configure Golem to load from this plugins directory and enable the plugin
    config = GolemConfig(
        content_dir=str(content),
        output_dir=str(tmp_path / "dist"),
        plugins=["test_hook"],
    )
    setattr(config, "plugins_dir", str(plugins_dir))

    engine = BuildEngine(config)
    engine.build_site()

    # Verify that the pre_parse and post_render hooks were applied to the compiled output!
    out_html = (tmp_path / "dist" / "index.html").read_text(encoding="utf-8")
    assert "final content." in out_html
    assert "Generated by Golem and Plugin" in out_html


def test_golem_add_subcommands_hookspec_execution():
    import click
    from click.testing import CliRunner
    from golem.plugins import get_plugin_manager, hookimpl

    pm = get_plugin_manager()

    class CustomCommandPlugin:
        @hookimpl
        def golem_add_subcommands(self, cli: click.Group) -> None:
            @cli.command("greet")
            @click.option("--name", default="World")
            def greet(name: str) -> None:
                click.echo(f"Hello, {name}!")

    pm.register(CustomCommandPlugin())

    @click.group()
    def test_cli():
        pass

    pm.hook.golem_add_subcommands(cli=test_cli)

    runner = CliRunner()
    result = runner.invoke(test_cli, ["greet", "--name", "Golem"])
    assert result.exit_code == 0
    assert "Hello, Golem!" in result.output


